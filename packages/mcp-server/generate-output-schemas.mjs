import ts from 'typescript';
import { format, resolveConfig } from 'prettier';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

// Derive wire contracts from actual handler return types, not names or example responses.
// JSON serialization drops undefined object properties and brands have no wire representation.
const root = dirname(fileURLToPath(import.meta.url));
const configPath = join(root, 'tsconfig.json');
const config = ts.readConfigFile(configPath, ts.sys.readFile);
const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, root);
const program = ts.createProgram(parsed.fileNames, parsed.options);
const checker = program.getTypeChecker();
const source = program.getSourceFile(join(root, 'src/tools.ts'));
const definitions = [];
function schema(type, ancestors = new Set()) {
  if (type.flags & (ts.TypeFlags.Any | ts.TypeFlags.Unknown)) return 'z.unknown()';
  if (type.flags & ts.TypeFlags.StringLiteral) return `z.literal(${JSON.stringify(type.value)})`;
  if (type.flags & ts.TypeFlags.NumberLiteral) return `z.literal(${type.value})`;
  if (type.flags & ts.TypeFlags.String) return 'z.string()';
  if (type.flags & ts.TypeFlags.Number) return 'z.number().finite()';
  if (type.flags & ts.TypeFlags.BooleanLiteral) return `z.literal(${type.intrinsicName})`;
  if (type.flags & ts.TypeFlags.Boolean) return 'z.boolean()';
  if (type.flags & ts.TypeFlags.Null) return 'z.null()';
  if (type.isIntersection() && type.types.some((t) => t.flags & ts.TypeFlags.String))
    return 'z.string()';
  if (type.isUnion()) {
    const members = type.types.filter((t) => !(t.flags & ts.TypeFlags.Undefined));
    const variants = [...new Set(members.map((t) => schema(t, ancestors)))];
    if (variants.length === 1) return variants[0];
    return `z.union([${variants.join(', ')}])`;
  }
  if (ancestors.has(type)) throw new Error(`Recursive output type: ${checker.typeToString(type)}`);
  const next = new Set([...ancestors, type]);
  if (checker.isArrayType(type))
    return `z.array(${schema(checker.getTypeArguments(type)[0], next)})`;
  if (checker.isTupleType(type))
    return `z.tuple([${checker
      .getTypeArguments(type)
      .map((t) => schema(t, next))
      .join(', ')}])`;
  const index = checker.getIndexTypeOfType(type, ts.IndexKind.String);
  if (index) return `z.record(${schema(index, next)})`;
  if (type.flags & ts.TypeFlags.Object) {
    const fields = checker.getPropertiesOfType(type).map((property) => {
      const field = checker.getTypeOfSymbolAtLocation(property, source);
      const optional =
        !!(property.flags & ts.SymbolFlags.Optional) ||
        (field.isUnion() && field.types.some((t) => t.flags & ts.TypeFlags.Undefined));
      return `${JSON.stringify(property.name)}: ${schema(field, next)}${optional ? '.optional()' : ''}`;
    });
    return `z.object({${fields.join(', ')}}).passthrough()`;
  }
  throw new Error(`Unsupported output type: ${checker.typeToString(type)}`);
}
function visit(node) {
  if (ts.isCallExpression(node) && node.expression.getText(source) === 'defineTool') {
    const spec = node.arguments[0];
    const name = spec.properties.find((p) => p.name?.getText(source) === 'name').initializer.text;
    const signature = checker.getSignatureFromDeclaration(node.arguments[1]);
    const type = checker.getAwaitedType(checker.getReturnTypeOfSignature(signature));
    // Both validation branches expose the same public fields; detailed error extras may vary.
    const result =
      name === 'document.validate'
        ? 'z.object({ok: z.boolean(), errors: z.array(z.object({code: z.string(), message: z.string()}).passthrough())}).passthrough()'
        : schema(type);
    if (!result.startsWith('z.object(')) throw new Error(`Non-object tool result: ${name}`);
    definitions.push([name, result]);
  }
  ts.forEachChild(node, visit);
}
visit(source);
definitions.sort(([a], [b]) => a.localeCompare(b, 'en'));
const result =
  '// Generated by generate-output-schemas.mjs from handler return types. Do not edit.\n' +
  "import { z } from 'zod';\n\n" +
  'export const toolOutputSchemas: Readonly<Record<string, z.AnyZodObject>> = {\n' +
  definitions.map(([name, value]) => `  ${JSON.stringify(name)}: ${value},`).join('\n') +
  '\n};\n';
const destination = join(root, 'src/output-schemas.ts');
const formatted = await format(result, {
  ...(await resolveConfig(destination)),
  filepath: destination,
});
if (process.argv.includes('--check')) {
  if ((await readFile(destination, 'utf8')) !== formatted)
    throw new Error('Tool output schemas are stale');
} else await writeFile(destination, formatted);
console.log(
  `Output contracts: ${definitions.length} tools ${process.argv.includes('--check') ? 'verified' : 'generated'}`,
);
